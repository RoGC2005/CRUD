    private Map<String, Integer> categorias =
        new HashMap<>();
    //PASO 8.3
    private void cargarCategorias() {
        JdCategoria.removeAllItems();
        categorias.clear();
        String sql =
            "SELECT id_categoria, nombre " +
            "FROM categoria " +
            "ORDER BY nombre";
        try (Connection cn = conexion.conectar();
             PreparedStatement ps = cn.prepareStatement(sql);
             ResultSet rs = ps.executeQuery()) {
            while (rs.next()) {
                int id = rs.getInt("id_categoria");
                String nombre = rs.getString("nombre");
                JdCategoria.addItem(nombre);
                categorias.put(nombre, id);
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(
                this,
                "Error al cargar categorías: " + e.getMessage()
            );
        }
    }
    //PASO 9
    private void listarProductos() {
        DefaultTableModel modelo = new DefaultTableModel(
            new Object[]{
                "ID", "Producto", "Categoría", "Precio", "Stock"
            }, 0
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        String sql =
            "SELECT p.id_producto, p.nombre, " +
            "c.nombre AS categoria, p.precio, p.stock " +
            "FROM producto p " +
            "INNER JOIN categoria c " +
            "ON p.id_categoria = c.id_categoria " +
            "ORDER BY p.id_producto";
        try (Connection cn = conexion.conectar();
             PreparedStatement ps = cn.prepareStatement(sql);
             ResultSet rs = ps.executeQuery()) {
            while (rs.next()) {
                Object[] fila = {
                    rs.getInt("id_producto"),
                    rs.getString("nombre"),
                    rs.getString("categoria"),
                    rs.getDouble("precio"),
                    rs.getInt("stock")
                };
                modelo.addRow(fila);
            }
            jTable.setModel(modelo);
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(
                this,
                "Error al listar productos: " + e.getMessage()
            );
        }
    }
    //PASO 10.1
    private boolean validarCampos() {
        if (JdProducto.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this,
                "Ingrese el nombre del producto");
            JdProducto.requestFocus();
            return false;
        }
        if (JdCategoria.getSelectedItem() == null) {
            JOptionPane.showMessageDialog(this,
                "Seleccione una categoría");
            return false;
        }
        if (JdPrecio.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this,
                "Ingrese el precio");
            JdPrecio.requestFocus();
            return false;
        }
        if (JdStock.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this,
                "Ingrese el stock");
            JdStock.requestFocus();
            return false;
        }
        return true;
    }
    //PASO 10.2
    private Double obtenerPrecioValido() {
        try {
            double precio = Double.parseDouble(
                JdPrecio.getText().trim()
            );
            if (precio <= 0) {
                JOptionPane.showMessageDialog(this,
                    "El precio debe ser mayor que cero");
                JdPrecio.requestFocus();
                return null;
            }
            return precio;
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                "Ingrese un precio válido");
            JdPrecio.requestFocus();
            return null;
        }
    }
    //PASO 10.3
    private Integer obtenerStockValido() {
        try {
            int stock = Integer.parseInt(
                JdStock.getText().trim()
            );
            if (stock < 0) {
                JOptionPane.showMessageDialog(this,
                    "El stock no puede ser negativo");
                JdStock.requestFocus();
                return null;
            }
            return stock;
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                "Ingrese un stock válido");
            JdStock.requestFocus();
            return null;
        }
    }
    //PASO 11.1
    private void limpiar() {
        Jid.setText("");
        JdProducto.setText("");
        JdPrecio.setText("");
        JdStock.setText("");
        if (JdCategoria.getItemCount() > 0) {
            JdCategoria.setSelectedIndex(0);
        }
        jTable.clearSelection();
    }

    //PASO 12
    private void guardarProducto() {
        if (!validarCampos()) {
            return;
        }
        Double precio = obtenerPrecioValido();
        if (precio == null) {
            return;
        }
        Integer stock = obtenerStockValido();
        if (stock == null) {
            return;
        }
        String nombre = JdProducto.getText().trim();
        String categoria = JdCategoria.getSelectedItem().toString();
        int idCategoria = categorias.get(categoria);
        String sql =
            "INSERT INTO producto " +
            "(nombre, id_categoria, precio, stock) " +
            "VALUES (?, ?, ?, ?)";
        try (Connection cn = conexion.conectar();
             PreparedStatement ps = cn.prepareStatement(sql)) {
            ps.setString(1, nombre);
            ps.setInt(2, idCategoria);
            ps.setDouble(3, precio);
            ps.setInt(4, stock);
            ps.executeUpdate();
            JOptionPane.showMessageDialog(this,
                "Producto registrado correctamente");
            listarProductos();
            limpiar();
            estadoInicial();
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                "Error al registrar: " + e.getMessage());
        }
    }

